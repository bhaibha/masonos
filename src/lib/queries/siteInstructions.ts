import { supabase } from '@/lib/supabase'
import type { NewSiInput, SiRow, SiStatus } from '@/lib/types'

const COLUMNS =
  'id, si_number, project_id, issued_date, vendor_id, addressed_to, work_area, ' +
  'instruction, attachments, has_cost_implication, variation_id, required_by, ' +
  'status, issued_by, acknowledged_at, completed_at, created_at, ' +
  'cancelled_at, cancelled_by, cancel_reason, vendors(name, phone)'

/**
 * Site instructions for one project, newest first.
 *
 * RLS `si_read` is `is_member(project_id)` with no role check — supervisors
 * included, because they're the ones acting on the instruction and the table
 * holds no figures. The linked VO's number is fetched separately and will come
 * back empty for a supervisor, since variation_orders is money-gated. That's
 * the intended outcome: they see "Cost implication: Yes" and nothing more.
 */
export async function fetchSiList(projectId: string): Promise<SiRow[]> {
  const { data, error } = await supabase
    .from('site_instructions')
    .select(COLUMNS)
    .eq('project_id', projectId)
    .order('issued_date', { ascending: false })
    .order('created_at', { ascending: false })
    .limit(300)

  if (error) throw error

  // The embedded `vendors(name)` join defeats PostgREST's type inference, so
  // the row shape is asserted once here rather than fought with at every field.
  const rows = (data ?? []) as unknown as Record<string, unknown>[]

  // Names for "issued by", and VO numbers where the caller may read them.
  const issuerIds = [...new Set(rows.map((r) => r.issued_by as string))]
  const voIds = [
    ...new Set(
      rows
        .map((r) => (r.variation_id as string | null) ?? null)
        .filter((v): v is string => Boolean(v)),
    ),
  ]

  const [people, vos] = await Promise.all([
    issuerIds.length
      ? supabase.from('profiles').select('id, full_name').in('id', issuerIds)
      : Promise.resolve({ data: [] as { id: string; full_name: string }[] }),
    voIds.length
      ? supabase.from('variation_orders').select('id, vo_number').in('id', voIds)
      : Promise.resolve({ data: [] as { id: string; vo_number: string }[] }),
  ])

  const nameById = new Map(
    (people.data ?? []).map((p) => [p.id as string, p.full_name as string]),
  )
  // Empty for supervisors — variation_orders RLS returns them nothing.
  const voById = new Map(
    (vos.data ?? []).map((v) => [v.id as string, v.vo_number as string]),
  )

  return rows.map((row) => {
    type V = { name: string; phone: string | null }
    const v = row.vendors as V | V[] | null
    const joined = Array.isArray(v) ? (v[0] ?? null) : v
    const registered = joined?.name ?? null
    const vendorId = (row.vendor_id as string | null) ?? null
    const variationId = (row.variation_id as string | null) ?? null

    return {
      id: row.id as string,
      si_number: row.si_number as string,
      project_id: row.project_id as string,
      issued_date: row.issued_date as string,
      vendor_id: vendorId,
      addressed_display: vendorId
        ? registered
        : ((row.addressed_to as string | null) ?? null),
      addressed_registered: vendorId !== null,
      // Only a linked vendor has a number on file; free text is just a name.
      addressed_phone: vendorId ? (joined?.phone ?? null) : null,
      work_area: (row.work_area as string | null) ?? null,
      instruction: row.instruction as string,
      attachments: (row.attachments as string[] | null) ?? [],
      has_cost_implication: Boolean(row.has_cost_implication),
      variation_id: variationId,
      variation_number: variationId ? (voById.get(variationId) ?? null) : null,
      required_by: (row.required_by as string | null) ?? null,
      status: row.status as SiStatus,
      issued_by: row.issued_by as string,
      issued_by_name: nameById.get(row.issued_by as string) ?? null,
      acknowledged_at: (row.acknowledged_at as string | null) ?? null,
      completed_at: (row.completed_at as string | null) ?? null,
      created_at: row.created_at as string,
      cancelled_at: (row.cancelled_at as string | null) ?? null,
      cancelled_by: (row.cancelled_by as string | null) ?? null,
      cancel_reason: (row.cancel_reason as string | null) ?? null,
    }
  })
}

/** Issues a new instruction. si_number is generated by the sequence. */
export async function createSi(input: NewSiInput): Promise<string> {
  const { data, error } = await supabase
    .from('site_instructions')
    .insert({
      project_id: input.project_id,
      issued_date: input.issued_date,
      vendor_id: input.vendor_id,
      addressed_to: input.addressed_to.trim() || null,
      work_area: input.work_area.trim() || null,
      instruction: input.instruction.trim(),
      attachments: input.attachments,
      has_cost_implication: input.has_cost_implication,
      variation_id: input.variation_id,
      required_by: input.required_by,
    })
    .select('id')
    .single()

  if (error) throw error
  return data.id as string
}

/**
 * Moves an instruction between issued / acknowledged / complete via
 * fn_set_si_status, which stamps the matching timestamps in the same statement
 * so status and dates cannot drift. Cancelling is a different path entirely
 * (fn_cancel_document) because it demands a reason.
 */
export async function setSiStatus(
  id: string,
  status: Exclude<SiStatus, 'cancelled'>,
): Promise<void> {
  const { error } = await supabase.rpc('fn_set_si_status', {
    p_id: id,
    p_status: status,
  })
  if (error) throw error
}

/** A still-outstanding instruction, trimmed to what the Tasks list shows. */
export interface OpenSi {
  id: string
  si_number: string
  instruction: string
  work_area: string | null
  required_by: string | null
  status: Exclude<SiStatus, 'complete' | 'cancelled'>
}

/**
 * Instructions still outstanding on a project — issued or acknowledged, but
 * not complete and not cancelled.
 *
 * Deliberately NOT date-filtered. A task belongs to a day; an instruction is
 * open until someone closes it, so it has to surface on the Tasks screen
 * whatever date is being viewed. That's the whole point of showing it there.
 *
 * Lean on purpose: no vendor join, no issuer lookup, no VO resolution — this
 * feeds a summary strip, not the full Instructions screen.
 */
export async function fetchOpenSis(projectId: string): Promise<OpenSi[]> {
  const { data, error } = await supabase
    .from('site_instructions')
    .select('id, si_number, instruction, work_area, required_by, status')
    .eq('project_id', projectId)
    .in('status', ['issued', 'acknowledged'])
    .order('required_by', { ascending: true, nullsFirst: false })
    .order('issued_date', { ascending: true })

  // A failure here must not take down the task list — it's supplementary.
  if (error) return []

  return (data ?? []).map((r) => ({
    id: r.id as string,
    si_number: r.si_number as string,
    instruction: r.instruction as string,
    work_area: (r.work_area as string | null) ?? null,
    required_by: (r.required_by as string | null) ?? null,
    status: r.status as OpenSi['status'],
  }))
}

/** Open variations on a project, for linking a cost-bearing instruction. */
export async function fetchLinkableVariations(
  projectId: string,
): Promise<{ id: string; label: string }[]> {
  const { data, error } = await supabase
    .from('variation_orders')
    .select('id, vo_number, title, status')
    .eq('project_id', projectId)
    .neq('status', 'cancelled')
    .order('created_at', { ascending: false })

  // Supervisors get nothing here by RLS — not an error, just an empty picker.
  if (error) return []
  return (data ?? []).map((v) => ({
    id: v.id as string,
    label: `${v.vo_number} · ${v.title as string}`,
  }))
}
