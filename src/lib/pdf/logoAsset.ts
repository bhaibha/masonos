/**
 * The Your Masons mark, inlined for jsPDF.
 *
 * WHY BASE64 AND NOT `public/logo-full.png`
 * -----------------------------------------
 * Every PDF generator in this app is SYNCHRONOUS — `generatePoPdf(opts): void`.
 * jsPDF's `addImage` will accept a URL string, but the bytes still have to be
 * in memory when the page is drawn, which means an `Image.onload` and an async
 * signature rippling through ten generators and every call site. Inlining the
 * artwork keeps them synchronous, and means a PO still prints with its
 * letterhead on a site phone that is offline.
 *
 * THE FORMAT WAS MEASURED, NOT GUESSED
 * ------------------------------------
 * 403x440 palette PNG (colour type 3) with a tRNS alpha table. Rendered at the
 * letterhead's 46pt that is ~690 dpi, so it stays crisp on a 600 dpi office
 * laser. Candidates were embedded through real jsPDF and rasterised at 300 dpi:
 * at 4x magnification a 64-colour palette is indistinguishable from full RGBA
 * (126 KB), while 32 colours starts to show tonal steps in the gradient.
 *
 * **`addImage` must be called with compression 'FAST'.** jsPDF re-encodes the
 * bitmap into the PDF and writes it UNCOMPRESSED by default: the same mark
 * costs 347 KB per document with no compression flag and 48 KB with one. That
 * is the difference between a purchase order a vendor can be emailed and one
 * they cannot. `drawLetterhead` passes it; anything drawing this by hand must
 * too.
 *
 * jsPDF keys images by their alias, so the same mark drawn on ten pages is
 * embedded once — a four-page document costs the same 48 KB as a one-page one.
 *
 * Regenerating: it is the tight-cropped gold-on-transparent artwork
 * (`public/logo-full.png`'s source at 1126x1230) resized to 440px tall and
 * quantised to 64 colours. Keep the aspect ratio below in step with it.
 */

